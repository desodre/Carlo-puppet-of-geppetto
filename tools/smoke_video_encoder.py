#!/usr/bin/env python3
"""Prove the synthetic H.264 encoder on an authorized device and decode it on the host.

Frames are generated by the agent with EGL/GLES; nothing here captures a display.
"""

from __future__ import annotations

import argparse
import json
import re
import shutil
import subprocess
from pathlib import Path

from android_session import ROOT, Adb, SessionError, run_session

NAL_NAMES = {1: "non_idr", 5: "idr", 7: "sps", 8: "pps"}


def nal_units(data: bytes) -> dict:
    """Count Annex B NAL unit types independently of the agent's own accounting."""
    counts = {"sps": 0, "pps": 0, "idr": 0, "non_idr": 0, "other": 0}
    position = data.find(b"\x00\x00\x01")
    if position not in (0, 1):
        raise SessionError("stream does not start with an Annex B start code")
    while position != -1:
        header = position + 3
        if header >= len(data) or data[header] & 0x80:
            raise SessionError("truncated or invalid NAL header")
        counts[NAL_NAMES.get(data[header] & 0x1F, "other")] += 1
        position = data.find(b"\x00\x00\x01", header)
    return counts


def validate_report(session: dict) -> dict:
    if session["exit_code"] != 0 or not session["cleanup_removed"]:
        raise SessionError("encoder probe failed or left its session directory")
    report = json.loads(session["stdout"])
    outcome, requested = report["outcome"], report["requested"]
    stream = outcome["stream"]
    units = stream["nal_units"]
    if report["source"] != "synthetic_egl_gles" or report["screen_capture"] is not False:
        raise SessionError("probe must declare a synthetic source and no screen capture")
    if report["video_available"] is not False:
        raise SessionError("synthetic proof must not announce a video capability")
    if not (
        outcome["error"] is None
        and stream["end_of_stream"]
        and outcome["frames_submitted"] == requested["frames"]
        and units["idr"] + units["non_idr"] == requested["frames"]
        and units["sps"] >= 1
        and units["pps"] >= 1
        and units["idr"] >= 1
        and stream["config_packets"] >= 1
        and stream["key_frames"] >= 1
        and stream["pts_non_decreasing"]
        and outcome["codec_name"]
        and (outcome["output_width"], outcome["output_height"])
        == (requested["width"], requested["height"])
    ):
        raise SessionError("encoder report does not prove a complete synthetic stream")
    return report


def validate_stream(data: bytes, requested: dict) -> dict:
    counts = nal_units(data)
    if not (
        counts["sps"] >= 1
        and counts["pps"] >= 1
        and counts["idr"] >= 1
        and counts["idr"] + counts["non_idr"] == requested["frames"]
    ):
        raise SessionError("dumped stream lacks parameter sets, an IDR or expected frames")
    return counts


def bar_left(requested: dict, index: int) -> int:
    """Left edge of the moving white bar drawn by the agent for frame `index`."""
    bar = max(requested["width"] // 8, 1)
    return int((requested["width"] - bar) * (index / requested["frames"]))


def validate_pixels(frames: bytes, requested: dict) -> dict:
    """Check decoded RGB frames show the generated bar and background, with tolerance."""
    width, height, count = requested["width"], requested["height"], requested["frames"]
    size = width * height * 3
    if len(frames) != size * count:
        raise SessionError("decoder did not produce the expected number of RGB frames")
    bar = max(width // 8, 1)

    def pixel(index, x):
        offset = index * size + ((height // 2) * width + x) * 3
        return tuple(frames[offset : offset + 3])

    checked = []
    for index in (0, count // 2, count - 1):
        left = bar_left(requested, index)
        inside = pixel(index, left + bar // 2)
        outside = pixel(index, (left + bar + width) // 2 if left < width // 2 else left // 2)
        if min(inside) < 200 or min(outside) > 120:
            raise SessionError("decoded frame does not show the synthetic bar pattern")
        checked.append({"frame": index, "bar_left": left})
    first, last = pixel(0, width - 4), pixel(count - 1, 4)
    if not (first[2] > first[0] + 60 and last[0] > last[2] + 60):
        raise SessionError("decoded background does not follow the synthetic color ramp")
    return {"frames_checked": checked, "background_ramp": True}


def decode(path: Path, requested: dict) -> dict:
    probe = subprocess.run(
        ["ffprobe", "-v", "error", "-count_frames", "-select_streams", "v:0", "-show_entries",
         "stream=codec_name,profile,width,height,pix_fmt,nb_read_frames", "-of", "json", str(path)],
        capture_output=True, text=True, timeout=60, check=True,
    )
    stream = json.loads(probe.stdout)["streams"][0]
    if not (
        stream["codec_name"] == "h264"
        and (stream["width"], stream["height"]) == (requested["width"], requested["height"])
        and int(stream["nb_read_frames"]) == requested["frames"]
    ):
        raise SessionError("host decoder disagrees with requested codec, size or frame count")
    raw = subprocess.run(
        ["ffmpeg", "-v", "error", "-xerror", "-i", str(path), "-f", "rawvideo",
         "-pix_fmt", "rgb24", "-"],
        capture_output=True, timeout=120, check=True,
    )
    return {"ffprobe": stream, **validate_pixels(raw.stdout, requested)}


def native_tests(adb: Adb, manifest: Path, physical: bool) -> dict:
    """Run only the video FFI tests of the library harness; keep their resource samples."""
    session = run_session(adb, manifest, "video-tests", 120, physical)
    stdout = session.get("stdout", "")
    marker = re.search(r"CARLO_VIDEO_RESOURCE_CYCLES (\{.*\})", stdout)
    if (session["exit_code"] != 0 or not session["cleanup_removed"] or marker is None
            or "test result: ok. 1 passed" not in stdout):
        raise SessionError("native video test failed, was filtered out or left its directory")
    return {"passed": 1, "fds_threads": json.loads(marker[1])}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--serial", required=True)
    parser.add_argument("--manifest", type=Path, default=ROOT / "dist/manifest.json")
    parser.add_argument("--output", type=Path, default=ROOT / "results/video-encoder")
    parser.add_argument("--cycles", type=int, default=3, help="extra probe sessions (0..20)")
    parser.add_argument("--allow-physical", action="store_true",
                        help="the owner authorized this physical device for this run")
    parser.add_argument("--tests-manifest", type=Path,
                        help="native test harness manifest; runs the video resource-cycle test")
    args = parser.parse_args()
    if not 0 <= args.cycles <= 20:
        parser.error("cycles must be in 0..20")
    if shutil.which("ffprobe") is None or shutil.which("ffmpeg") is None:
        parser.error("host decode check requires ffmpeg and ffprobe")
    adb = Adb(args.serial)
    physical = args.allow_physical
    manifest = args.manifest.resolve()
    args.output.mkdir(parents=True, exist_ok=True)
    report = validate_report(run_session(adb, manifest, "video-encode-probe", 30, physical))
    for _ in range(args.cycles):
        validate_report(run_session(adb, manifest, "video-encode-probe", 30, physical))
    stream_path = args.output / "synthetic.h264"
    dump = run_session(adb, manifest, "video-encode-dump", 30, physical, stream_path)
    if dump["exit_code"] != 0 or not dump["cleanup_removed"] or dump["stderr"]:
        raise SessionError("stream dump failed, wrote diagnostics or left its directory")
    requested = report["requested"]
    counts = validate_stream(stream_path.read_bytes(), requested)
    summary = {
        "emulator": dump["emulator"],
        "android_api": dump["android_api"],
        "abi": dump["abi"],
        "source": "synthetic_egl_gles",
        "screen_capture": False,
        "agent_manifest": json.loads(manifest.read_text()),
        "probe_report": report,
        "probe_sessions": args.cycles + 1,
        "dump": {key: dump[key] for key in ("stdout_bytes", "stdout_sha256", "cleanup_removed")},
        "host_nal_units": counts,
        "host_decode": decode(stream_path, requested),
    }
    if args.tests_manifest:
        summary["native_tests"] = native_tests(adb, args.tests_manifest.resolve(), physical)
    (args.output / "summary.json").write_text(json.dumps(summary, indent=2) + "\n")
    print("Synthetic H.264 encoded natively, drained and decoded on the host; sessions cleaned up.")


if __name__ == "__main__":
    try:
        main()
    except (SessionError, subprocess.SubprocessError, OSError, ValueError, KeyError) as error:
        raise SystemExit(f"carlo-video-smoke: {error}") from error
